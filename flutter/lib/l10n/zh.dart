/// The interface in Chinese.
///
/// `tr()` takes the English the editor already draws and returns the Chinese for it, so the
/// translation of a label lives in one table instead of at every call site. Two kinds of English
/// pass through it:
///
///   * the editor's own chrome — menus, buttons, dialogs, the words in `ui/` and `app/`;
///   * the control catalogue's titles, which arrive as data from
///     web/src/generated/controls.js via tool/prepare.sh and are handed to `tr()` in
///     model/catalogue.dart, so every slider label and group is covered by one hook.
///
/// What is deliberately *not* translated: the film stocks, papers and lenses themselves. Kodak
/// Portra 400, Fuji Velvia, Ilford HP5, Pro-Mist 1/8, #21 Orange and the rest are proper names
/// printed on the box, and a photographer looking for "Portra 400" must find "Portra 400".
///
/// Terminology follows Chinese photographic post-production usage: Exposure 曝光, Highlights 高光,
/// Shadows 阴影, Contrast 对比度, Saturation 饱和度, Vibrance 自然饱和度, Temperature 色温, Tint 色调,
/// Grain 颗粒, Halation 光晕, White Balance 白平衡.
library;

/// Whether the interface is drawn in Chinese. The shipped Android build is Chinese; the desktop
/// and browser editors default to English unless FOTUFILM_LOCALE=zh is set (see app/app.dart).
bool _chinese = true;

bool get interfaceIsChinese => _chinese;

set interfaceIsChinese(bool value) => _chinese = value;

/// Chinese for [english], or [english] itself when the table has no entry — an untranslated
/// label reads as the original rather than as a missing key.
String tr(String english) {
  if (!_chinese) return english;
  return zhOf[english] ?? english;
}

/// The same, for text that is a sentence with values in it. Only the words the document states
/// are replaced, so an unknown shape passes through untouched.
String trText(String english) {
  if (!_chinese) return english;
  final exact = zhOf[english];
  if (exact != null) return exact;
  var text = english;
  for (final MapEntry(:key, :value) in _phrases.entries) {
    if (text.contains(key)) text = text.replaceAll(key, value);
  }
  return text;
}

/// Multi-word phrases, longest first, for trText().
final Map<String, String> _phrases = Map.fromEntries(
    zhOf.entries.where((e) => e.key.contains(' ')).toList()
      ..sort((a, b) => b.key.length.compareTo(a.key.length)));

